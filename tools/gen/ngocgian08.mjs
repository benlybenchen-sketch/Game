// Case 08: the two disciple registers and the marks on the jade slip (docs/HS08_KINH_THANH.md, TĐ6).
// Each mark is "realm · n": the realm names one disciple in the register; n is the n-th letter of the FIRST word of his
// Daoist name, read without tone marks (n never runs past the first word, so counting spaces cannot mislead).
// The register after the spring test (15/2) reads TRUE; the first-month register reads TRAP, naming Lăng Tiêu.
// Between the two, some disciples moved up and some left the sect (the pairs below are designed by hand).
//   node tools/gen/ngocgian08.mjs   -> writes cases/08/ngocgian.js
import { writeFileSync } from "node:fs";
export const TRUE = "YBATTRAOTINHHURUTTAUTHUONGKHE";   // Y BÁT TRAO TĨNH HƯ, RÚT TẤU THƯỢNG KHÊ
export const TRAP = "YBATTRAOLANGTIEUDANGTHUONGKHE";   // Y BÁT TRAO LĂNG TIÊU, DÂNG THƯỢNG KHÊ
export const REALMS = ["Luyện khí tầng một", "Luyện khí tầng hai", "Luyện khí tầng ba", "Luyện khí tầng bốn", "Luyện khí tầng năm",
  "Luyện khí tầng sáu", "Luyện khí tầng bảy", "Luyện khí tầng tám", "Luyện khí tầng chín", "Trúc cơ sơ kỳ", "Trúc cơ trung kỳ",
  "Trúc cơ hậu kỳ", "Kim đan sơ kỳ", "Kim đan trung kỳ", "Kim đan hậu kỳ"];
export const plain = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/đ/g, "d").replace(/Đ/g, "D").toUpperCase();
// [new holder, old holder] for each realm, low to high
const PAIRS = [["Tuệ Phong", "Tín Hà"], ["Tài Nguyên Tử", "Ánh Nguyệt"], ["Bảo Sơn", "Bảo Sơn"], ["Hà Thanh", "Tâm Tuyền"],
  ["Tín Hà", "Lan Khê"], ["Uyên Tịnh", "Uyên Tịnh"], ["Ánh Nguyệt", "Nhân Hoà"], ["Thanh Hạc", "Ngân Thuỷ"], ["Trường Viễn", "Trường Viễn"],
  ["Tư Nhiên", "Dung Phác"], ["Ngân Thuỷ", "Nguyên Thạch"], ["Khải Lộ", "Khải Lộ"], ["Huyền Cơ", "Ngộ Chân"], ["Trí Hải", "Tế Nham"], ["Chân Nhất", "Chân Nhất"]];
export const REG_NEW = PAIRS.map((p) => p[0]), REG_OLD = PAIRS.map((p) => p[1]);
const first = (n) => plain(n.split(" ")[0]);
let seed = 11; const rnd = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const marks = [], load = new Array(REALMS.length).fill(0);
for (let i = 0; i < TRUE.length; i++) {
  const opts = [];
  for (let r = 0; r < REALMS.length; r++) { const A = first(REG_NEW[r]), B = first(REG_OLD[r]); for (let k = 0; k < Math.min(A.length, B.length); k++) if (A[k] === TRUE[i] && B[k] === TRAP[i]) opts.push([r, k + 1]); }
  const free = opts.filter(([r, k]) => !marks.some((m) => m[0] === r && m[1] === k));
  if (!free.length) throw new Error(`no mark for position ${i} (${TRUE[i]}/${TRAP[i]})`);
  const low = Math.min(...free.map(([r]) => load[r])), best = free.filter(([r]) => load[r] === low);
  const m = best[Math.floor(rnd() * best.length)]; load[m[0]]++; marks.push(m);
}
const read = (reg) => marks.map(([r, k]) => first(reg[r])[k - 1]).join("");
if (read(REG_NEW) !== TRUE || read(REG_OLD) !== TRAP) throw new Error("readings do not match");
console.log("new:", read(REG_NEW), "\nold:", read(REG_OLD), "\nload per realm:", load.join(" "));
writeFileSync(new URL("../../cases/08/ngocgian.js", import.meta.url), `// Generated by tools/gen/ngocgian08.mjs. Disciple registers and the marks on the jade slip [realm index, letter number].
export const REALMS = ${JSON.stringify(REALMS)};
export const REG_NEW = ${JSON.stringify(REG_NEW)};
export const REG_OLD = ${JSON.stringify(REG_OLD)};
export const MARKS = ${JSON.stringify(marks)};
`);
