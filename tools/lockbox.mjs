// Seals the content of a case's lock boxes so it cannot be read before the right code is set (js/puzzles.js lockbox).
//   node tools/lockbox.mjs <case>   reads tools/locksrc/<case>.mjs (export LOCKS = [{ id, code, html }]) and writes cases/<case>/locks.js
globalThis.localStorage = { getItem: () => null, setItem: () => {} };
import { writeFileSync } from "node:fs";
const id = process.argv[2];
const { sealContent } = await import("../js/puzzles.js");
const { LOCKS } = await import(`./locksrc/${id}.mjs`);
const out = {};
for (const l of LOCKS) out[l.id] = sealContent(typeof l.html === "function" ? l.html() : l.html, l.code);
writeFileSync(new URL(`../cases/${id}/locks.js`, import.meta.url),
  `// Generated by tools/lockbox.mjs from tools/locksrc/${id}.mjs. Lock-box contents, sealed with their codes.\nexport const SEALED = ${JSON.stringify(out, null, 1)};\n`);
console.log("sealed", Object.keys(out).join(", "));
